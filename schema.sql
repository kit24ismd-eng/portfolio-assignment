-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  email text not null,
  role text not null check (role in ('Customer', 'Provider')),
  appointment_date date not null,
  appointment_time time not null,
  service text not null,
  message text not null default '',
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'cancelled', 'completed')),
  created_at timestamptz not null default now()
);

-- The Python API uses the service-role key, stored only in Vercel environment variables.
-- Do not put that key in HTML, JavaScript, GitHub, or any VITE_/NEXT_PUBLIC_ variable.
alter table public.appointments enable row level security;
-- No public policies are created. Public visitors cannot read or write directly;
-- inserts are performed by the server-side Python API using the secret service-role key.
